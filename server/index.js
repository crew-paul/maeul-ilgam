import 'dotenv/config';
import express from 'express';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {openDatabase} from './db.js';
import {createApp} from './app.js';
if(process.env.NODE_ENV==='production'&&process.env.AUTH_MODE==='development')throw new Error('Development authentication is forbidden in production');
if(process.env.NODE_ENV==='production'&&!process.env.APP_ORIGIN?.startsWith('https://'))throw new Error('Production requires HTTPS APP_ORIGIN');
const db=await openDatabase();const app=createApp(db);const dist=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../dist');app.use(express.static(dist));app.get('*',(_req,res)=>res.sendFile(path.join(dist,'index.html')));const server=app.listen(process.env.PORT||3001,process.env.HOST||'127.0.0.1',()=>console.log(`Ma-eul Ilgam listening on ${process.env.PORT||3001}`));
async function stop(){server.close(async()=>{await db.close();process.exit(0)})}process.on('SIGTERM',stop);process.on('SIGINT',stop);
